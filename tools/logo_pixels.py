#!/usr/bin/env python3
"""Turn assets/gvisor-logo.png into gvdemo/logo_pixels.py: the logo as pixel
art, one character per pixel ('.' clear, 'n' navy, 'w' white, 'g' gold,
't' the navy lettering, kept apart so it can be recoloured), at a few
scales. Run it again only if the logo changes. Standard library only
(the PNG is decoded with zlib), so the demo needs no image library.
"""

import collections
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SCALES = (3, 4, 5, 6, 8)  # source pixels per art pixel; the page uses the
                          # largest art that fits the window
HELMET_W = 230  # the helmet is the logo's left 230 source pixels


def load_png(path):
    """(width, height, rows of RGBA tuples) for an 8-bit RGBA PNG."""
    d = path.read_bytes()
    assert d[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    i, idat = 8, b""
    while i < len(d):
        n, kind = struct.unpack(">I4s", d[i:i + 8])
        body = d[i + 8:i + 8 + n]
        i += 12 + n
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB",
                                                                body)
        elif kind == b"IDAT":
            idat += body
    assert (depth, ctype, interlace) == (8, 6, 0), "need 8-bit RGBA"
    raw, bpp = zlib.decompress(idat), 4
    stride = w * bpp
    rows, prev, p = [], bytearray(stride), 0
    for _ in range(h):
        f, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pred = a if pa <= pb and pa <= pc else b if pb <= pc else c
                line[x] = (line[x] + pred) & 255
        rows.append([tuple(line[x:x + 4]) for x in range(0, stride, 4)])
        prev = line
    return w, h, rows


def kind(px):
    r, g, b, a = px
    if a < 128:
        return "."
    if r > 200 and g > 200 and b > 200:
        return "w"
    if r > 200 and g > 120:
        return "g"
    return "n"


def pixelate(w, h, rows, s):
    """One art pixel per block of source pixels. The art is drawn with
    quadrant blocks, 2 x 2 pixels per character cell, and a cell is about
    twice as tall as it is wide, so a block is s/2 wide and s tall.

    Gold wins at 20% of a block, so the small stars survive. Navy wins at
    25% in the helmet, whose lines are thin, and at 40% in the lettering,
    so its counters (the hole in "o") stay open."""
    sx, sy = s / 2, s
    art = []
    for j in range(int(h / sy)):
        y0, y1 = round(j * sy), round((j + 1) * sy)
        line = ""
        for i in range(int(w / sx)):
            x0, x1 = round(i * sx), round((i + 1) * sx)
            c = collections.Counter(kind(rows[yy][xx])
                                    for yy in range(y0, y1)
                                    for xx in range(x0, x1))
            n = (y1 - y0) * (x1 - x0)
            if c["g"] >= 0.2 * n:
                line += "g"
            elif c["n"] >= (0.25 if x0 < HELMET_W else 0.4) * n:
                line += "n" if x0 < HELMET_W else "t"
            else:
                line += c.most_common(1)[0][0]
        art.append(line)
    return art


def main():
    w, h, rows = load_png(HERE / "assets" / "gvisor-logo.png")
    out = ['"""The gVisor logo as pixel art. Generated by tools/logo_pixels.py',
           'from assets/gvisor-logo.png; do not edit."""', "", "ART = {"]
    for s in SCALES:
        out.append(f"    {s}: [")
        out += [f'        "{line}",' for line in pixelate(w, h, rows, s)]
        out.append("    ],")
    out.append("}")
    (HERE / "gvdemo" / "logo_pixels.py").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
